/** 按关键词匹配本地兜底回复 */
export function matchLocalReply(text) {
  const lower = String(text || '').toLowerCase();
  const hit = LOCAL_RULES.find((rule) =>
    rule.keywords.some((k) => lower.includes(k.toLowerCase()))
  );
  return hit ? hit.reply : DEFAULT_REPLY;
}

